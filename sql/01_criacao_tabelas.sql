-- Apaga as tabelas se já existirem (permite rodar o script de novo)
DROP VIEW  IF EXISTS vw_vaga_resumo;
DROP VIEW  IF EXISTS vw_candidato_idade;
DROP TABLE IF EXISTS candidatura;
DROP TABLE IF EXISTS curriculo;
DROP TABLE IF EXISTS candidato_telefone;
DROP TABLE IF EXISTS vaga;
DROP TABLE IF EXISTS candidato;
DROP TABLE IF EXISTS consultor;
DROP TABLE IF EXISTS empresa_cliente;

-- ---------------------------------------------------------------------
-- EMPRESA_CLIENTE: empresas que contratam a consultoria para recrutar
-- Endereço é atributo COMPOSTO (logradouro, numero, bairro, cidade, uf, cep)
-- ---------------------------------------------------------------------
CREATE TABLE empresa_cliente (
    id_empresa      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    razao_social    VARCHAR(120) NOT NULL,
    cnpj            CHAR(14)     NOT NULL UNIQUE,
    ramo_atividade  VARCHAR(60)  NOT NULL,
    email_contato   VARCHAR(120) NOT NULL,
    logradouro      VARCHAR(120) NOT NULL,
    numero          VARCHAR(10)  NOT NULL,
    bairro          VARCHAR(60)  NOT NULL,
    cidade          VARCHAR(60)  NOT NULL,
    uf              CHAR(2)      NOT NULL,
    cep             CHAR(8)      NOT NULL,
    data_cadastro   DATE         NOT NULL DEFAULT CURRENT_DATE
);

-- ---------------------------------------------------------------------
-- CONSULTOR: profissionais de RH que conduzem os processos seletivos
-- ---------------------------------------------------------------------
CREATE TABLE consultor (
    id_consultor     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome             VARCHAR(100) NOT NULL,
    cpf              CHAR(11)     NOT NULL UNIQUE,
    email            VARCHAR(120) NOT NULL UNIQUE,
    especialidade    VARCHAR(60)  NOT NULL,
    salario          DECIMAL(10,2) NOT NULL CHECK (salario > 0),
    data_contratacao DATE         NOT NULL
);

-- ---------------------------------------------------------------------
-- CANDIDATO: pessoas que procuram emprego pela consultoria
-- data_nascimento gera o atributo DERIVADO idade (ver view)
-- ---------------------------------------------------------------------
CREATE TABLE candidato (
    id_candidato    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome            VARCHAR(100) NOT NULL,
    cpf             CHAR(11)     NOT NULL UNIQUE,
    email           VARCHAR(120) NOT NULL UNIQUE,
    data_nascimento DATE         NOT NULL,
    logradouro      VARCHAR(120) NOT NULL,
    numero          VARCHAR(10)  NOT NULL,
    bairro          VARCHAR(60)  NOT NULL,
    cidade          VARCHAR(60)  NOT NULL,
    uf              CHAR(2)      NOT NULL,
    cep             CHAR(8)      NOT NULL
);

-- ---------------------------------------------------------------------
-- CANDIDATO_TELEFONE: atributo MULTIVALORADO telefone do candidato
-- (um candidato pode ter vários telefones)
-- ---------------------------------------------------------------------
CREATE TABLE candidato_telefone (
    id_telefone   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_candidato  INT         NOT NULL,
    telefone      VARCHAR(15) NOT NULL,
    tipo          VARCHAR(15) NOT NULL CHECK (tipo IN ('Celular', 'Residencial', 'Recado')),
    CONSTRAINT fk_telefone_candidato FOREIGN KEY (id_candidato)
        REFERENCES candidato (id_candidato) ON DELETE CASCADE,
    CONSTRAINT uq_candidato_telefone UNIQUE (id_candidato, telefone)
);

-- ---------------------------------------------------------------------
-- CURRICULO: relacionamento 1:1 com CANDIDATO
-- O UNIQUE em id_candidato garante que cada candidato tenha só 1 currículo
-- ---------------------------------------------------------------------
CREATE TABLE curriculo (
    id_curriculo       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_candidato       INT          NOT NULL UNIQUE,
    escolaridade       VARCHAR(40)  NOT NULL,
    area_formacao      VARCHAR(60)  NOT NULL,
    anos_experiencia   INT          NOT NULL CHECK (anos_experiencia >= 0),
    pretensao_salarial DECIMAL(10,2) NOT NULL CHECK (pretensao_salarial > 0),
    data_atualizacao   DATE         NOT NULL,
    CONSTRAINT fk_curriculo_candidato FOREIGN KEY (id_candidato)
        REFERENCES candidato (id_candidato) ON DELETE CASCADE
);

-- ---------------------------------------------------------------------
-- VAGA: vagas abertas pelas empresas clientes
-- 1:N com EMPRESA_CLIENTE (uma empresa abre várias vagas)
-- 1:N com CONSULTOR (um consultor é responsável por várias vagas)
-- ---------------------------------------------------------------------
CREATE TABLE vaga (
    id_vaga        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empresa     INT           NOT NULL,
    id_consultor   INT           NOT NULL,
    titulo         VARCHAR(80)   NOT NULL,
    area           VARCHAR(60)   NOT NULL,
    salario        DECIMAL(10,2) NOT NULL CHECK (salario > 0),
    modalidade     VARCHAR(15)   NOT NULL CHECK (modalidade IN ('Presencial', 'Remoto', 'Híbrido')),
    data_abertura  DATE          NOT NULL,
    status         VARCHAR(15)   NOT NULL DEFAULT 'Aberta'
                   CHECK (status IN ('Aberta', 'Em seleção', 'Preenchida', 'Cancelada')),
    CONSTRAINT fk_vaga_empresa FOREIGN KEY (id_empresa)
        REFERENCES empresa_cliente (id_empresa) ON DELETE RESTRICT,
    CONSTRAINT fk_vaga_consultor FOREIGN KEY (id_consultor)
        REFERENCES consultor (id_consultor) ON DELETE RESTRICT
);

-- ---------------------------------------------------------------------
-- CANDIDATURA: relacionamento N:N entre CANDIDATO e VAGA
-- Um candidato se candidata a várias vagas e uma vaga recebe vários candidatos
-- ---------------------------------------------------------------------
CREATE TABLE candidatura (
    id_candidatura    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_candidato      INT          NOT NULL,
    id_vaga           INT          NOT NULL,
    data_candidatura  DATE         NOT NULL,
    status            VARCHAR(20)  NOT NULL DEFAULT 'Inscrito'
                      CHECK (status IN ('Inscrito', 'Entrevista', 'Aprovado', 'Reprovado')),
    nota_entrevista   DECIMAL(4,2) CHECK (nota_entrevista BETWEEN 0 AND 10),
    CONSTRAINT fk_candidatura_candidato FOREIGN KEY (id_candidato)
        REFERENCES candidato (id_candidato) ON DELETE CASCADE,
    CONSTRAINT fk_candidatura_vaga FOREIGN KEY (id_vaga)
        REFERENCES vaga (id_vaga) ON DELETE CASCADE,
    CONSTRAINT uq_candidatura UNIQUE (id_candidato, id_vaga)
);

-- ---------------------------------------------------------------------
-- ATRIBUTOS DERIVADOS (calculados, não ficam gravados)
-- ---------------------------------------------------------------------

-- idade do candidato: derivada de data_nascimento
CREATE VIEW vw_candidato_idade AS
SELECT id_candidato,
       nome,
       data_nascimento,
       DATE_PART('year', AGE(CURRENT_DATE, data_nascimento))::INT AS idade
FROM candidato;

-- total de candidatos por vaga: derivado da contagem de candidaturas
CREATE VIEW vw_vaga_resumo AS
SELECT v.id_vaga,
       v.titulo,
       v.status,
       COUNT(c.id_candidatura) AS total_candidatos
FROM vaga v
LEFT JOIN candidatura c ON c.id_vaga = v.id_vaga
GROUP BY v.id_vaga, v.titulo, v.status;
